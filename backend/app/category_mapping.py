def get_creator_display_name(username: str) -> str:
    """Returns human-friendly display name or falls back to capitalized username."""
    if not username:
        return "Unknown"
    norm = username.strip().lower()
    return CREATOR_DISPLAY_NAMES.get(norm, username.replace(".", " ").replace("_", " ").title())

def get_creator_category(username: str, default: str = "Uncategorized") -> str:
    """Returns verified category for handle."""
    if not username:
        return default
    return CREATOR_CATEGORIES.get(username.strip().lower(), default)

def get_creator_country(username: str, current_country: str = None) -> str:
    """Returns clean country with optional enrichment."""
    if current_country and str(current_country).strip() and str(current_country).lower() not in ["nan", "none", "null"]:
        return str(current_country).strip()
    norm = username.strip().lower() if username else ""
    return VERIFIED_COUNTRIES.get(norm, "Unspecified")
